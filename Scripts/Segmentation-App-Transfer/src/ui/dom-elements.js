/** Resolve the registry against a Document-compatible query root. */
export function getDomElements(queryRoot) {
  if (!queryRoot || typeof queryRoot.querySelector !== "function") {
    throw new TypeError("A DOM query root is required");
  }
  return Object.fromEntries(
    Object.entries(DOM_SELECTORS).map(([name, selector]) => [
      name,
      queryRoot.querySelector(selector),
    ])
  );
}
